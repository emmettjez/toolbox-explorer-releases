#!/usr/bin/env bash
#
# Build a static, LGPL ffmpeg + ffprobe for Toolbox Explorer to bundle
# (EXPLORER.md §5.4 · §6; adapted from the render-browser build script).
#
# Why build rather than download: every ready-made macOS static build
# (evermeet.cx, OSXExperts, Homebrew) is GPL, because they bundle x264/x265.
# Explorer encodes proxies with h264_videotoolbox (Apple's encoder, no GPL part)
# and only ever DECODES EXR/DPX/ProRes/…, so it needs no GPL component — and an
# LGPL binary is the difference between "can ship this" and "cannot".
#
# What is in it beyond the render-browser build:
#   --enable-libzimg      zscale for linear→sRGB/709 (zimg is WTFPL; linked STATIC,
#                         built from a pinned git commit in the work dir — nothing
#                         from Homebrew leaks in)
#   --enable-audiotoolbox AAC via Apple's encoder for movies with audio
#   --enable-videotoolbox H.264/HEVC hardware encode + ProRes/H.264 HW decode
#
# Deliberately NOT a --disable-everything minimal build: durability over size.
#
#   ./tools/build-ffmpeg.sh                 # arm64 (the shipping target)
#   ./tools/build-ffmpeg.sh --arch x86_64   # Intel, or --universal for both
#   ./tools/build-ffmpeg.sh --verify-only   # re-run the checks, no rebuild
#   ./tools/build-ffmpeg.sh --sign "Developer ID Application: …"   # else ad-hoc
#
# Output: vendor/ffmpeg/{ffmpeg,ffprobe}  (gitignored)
# Work:   out/ffmpeg-build/                         (gitignored)
#
set -euo pipefail

# 8.1.2 deliberately: every measurement in the S1 spike report was taken against
# this exact version (it is also what Homebrew ships).
FFMPEG_VERSION="${FFMPEG_VERSION:-8.1.2}"

# Pinned tarball hash. Empty means "not yet pinned" and the script REFUSES to build
# unless --trust-first-download is passed. A check that cannot tell "verified" from
# "never ran" is not a check.
#
# Provenance: ffmpeg.org publishes a GPG .asc but NO .sha256, and gpg is not
# installed here. This value is Homebrew's pinned checksum for the identical URL
# (`brew info --json=v2 ffmpeg`), which is an independent, reviewed source rather
# than trust-on-first-use. Re-derive it the same way when bumping the version.
FFMPEG_SHA256="${FFMPEG_SHA256:-464beb5e7bf0c311e68b45ae2f04e9cc2af88851abb4082231742a74d97b524c}"

# zimg: pinned to a git TAG *and* the commit it must resolve to. A tag can be moved;
# a commit hash cannot. The release has no tarball asset and GitHub's autogenerated
# archives are not guaranteed byte-stable, so git + commit pin is the honest pin.
ZIMG_VERSION="${ZIMG_VERSION:-3.0.6}"
ZIMG_TAG="release-$ZIMG_VERSION"
ZIMG_COMMIT="${ZIMG_COMMIT:-f819b14e8f39d1282400b0d9543e8ef73c1b2bbd}"
ZIMG_REPO="https://github.com/sekrit-twc/zimg"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# 🔴 The app is the repo ROOT since the port — main/ffmpeg.js resolves
# `<repo>/vendor/ffmpeg`. This said $ROOT/desktop/vendor, a leftover from when
# Explorer lived in ae-toolbox/desktop, and it silently rebuilt the old nesting
# INSIDE the new repo: 41 MB of correct binaries in a directory nothing reads.
VENDOR="$ROOT/vendor/ffmpeg"
WORK="${WORK:-$ROOT/out/ffmpeg-build}"
ARCHS=(arm64)
TRUST_FIRST=0
VERIFY_ONLY=0
SIGN_ID=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --arch) ARCHS=("$2"); shift 2 ;;
    --universal) ARCHS=(arm64 x86_64); shift ;;
    --sign) SIGN_ID="$2"; shift 2 ;;
    --trust-first-download) TRUST_FIRST=1; shift ;;
    --verify-only) VERIFY_ONLY=1; shift ;;
    -h|--help) sed -n '2,30p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

say() { printf '\033[1m==>\033[0m %s\n' "$*"; }
die() { printf '\033[31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

command -v curl >/dev/null || die "curl not found"
command -v git >/dev/null || die "git not found"
command -v make >/dev/null || die "make not found - install Xcode command line tools"
command -v pkg-config >/dev/null || die "pkg-config not found (brew install pkg-config) - ffmpeg's configure needs it to find libzimg"
xcode-select -p >/dev/null 2>&1 || die "no Xcode command line tools: xcode-select --install"
command -v nasm >/dev/null || say "nasm not found - x86_64 build will be slower but will work (irrelevant for arm64)"

mkdir -p "$WORK" "$VENDOR"
if [[ "$VERIFY_ONLY" -eq 1 ]]; then
  [[ -x "$VENDOR/ffmpeg" ]] || die "nothing to verify - $VENDOR/ffmpeg does not exist. Build first."
  say "verify-only: skipping fetch and build"
fi
TARBALL="$WORK/ffmpeg-$FFMPEG_VERSION.tar.xz"
SRC="$WORK/ffmpeg-$FFMPEG_VERSION"
ZIMG_SRC="$WORK/zimg-$ZIMG_VERSION"

# ---------------------------------------------------------------- fetch ffmpeg
if [[ "$VERIFY_ONLY" -eq 0 ]] && [[ ! -f "$TARBALL" ]]; then
  say "downloading ffmpeg $FFMPEG_VERSION source (~10 MB) from ffmpeg.org"
  curl -fLS --proto '=https' --tlsv1.2 \
    -o "$TARBALL" "https://ffmpeg.org/releases/ffmpeg-$FFMPEG_VERSION.tar.xz"
fi

if [[ "$VERIFY_ONLY" -eq 0 ]]; then
ACTUAL_SHA="$(shasum -a 256 "$TARBALL" | awk '{print $1}')"
if [[ -z "$FFMPEG_SHA256" ]]; then
  if [[ "$TRUST_FIRST" -eq 1 ]]; then
    say "UNVERIFIED first download. Pin this in the script before trusting the build:"
    printf '\n    FFMPEG_SHA256="%s"\n\n' "$ACTUAL_SHA"
  else
    die "FFMPEG_SHA256 is not pinned, so the tarball cannot be verified.
  Downloaded hash: $ACTUAL_SHA
  Cross-check it against https://ffmpeg.org/download.html, paste it into this
  script, and re-run. To proceed anyway: --trust-first-download"
  fi
elif [[ "$ACTUAL_SHA" != "$FFMPEG_SHA256" ]]; then
  die "tarball checksum MISMATCH - refusing to build.
  expected $FFMPEG_SHA256
  actual   $ACTUAL_SHA"
else
  say "ffmpeg tarball checksum verified"
fi
[[ -d "$SRC" ]] || { say "extracting ffmpeg"; tar -xf "$TARBALL" -C "$WORK"; }

# ---------------------------------------------------------------- fetch zimg
if [[ ! -d "$ZIMG_SRC/.git" ]]; then
  say "cloning zimg $ZIMG_TAG"
  rm -rf "$ZIMG_SRC"
  git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$ZIMG_TAG" "$ZIMG_REPO" "$ZIMG_SRC"
fi
ZIMG_ACTUAL="$(git -C "$ZIMG_SRC" rev-parse HEAD)"
if [[ "$ZIMG_ACTUAL" != "$ZIMG_COMMIT" ]]; then
  die "zimg $ZIMG_TAG resolved to commit $ZIMG_ACTUAL, expected $ZIMG_COMMIT - the tag moved. Refusing to build."
fi
say "zimg commit verified ($ZIMG_COMMIT)"
fi

# ---------------------------------------------------------------- build zimg
# zimg is autotools, and automake is not on a stock Mac (nor in the dependency
# list of anything else here). It is ~60 C++ files with no configure-time
# discovery worth the name (the only platform switch is ZIMG_ARM vs ZIMG_X86), so
# compile it directly: same flags configure.ac/Makefile.am would use, one .a, one
# hand-written zimg.pc. Pinned to one commit, so the source list below is stable;
# bump ZIMG_VERSION and re-check Makefile.am together.
build_zimg() {
  local arch="$1" out="$2"
  local flags=(-std=c++14 -O2 -DNDEBUG -fvisibility=hidden -I"$ZIMG_SRC/src/zimg"
               -arch "$arch" -mmacosx-version-min=11.0)
  local srcs=()
  # common list = Makefile.am libzimg_internal_la_SOURCES (the .cpp entries)
  for d in api colorspace common depth graph resize unresize; do
    while IFS= read -r f; do srcs+=("$f"); done < <(find "$ZIMG_SRC/src/zimg/$d" -maxdepth 1 -name '*.cpp' | sort)
  done
  case "$arch" in
    arm64)
      flags+=(-DZIMG_ARM)
      while IFS= read -r f; do srcs+=("$f"); done < <(find "$ZIMG_SRC/src/zimg" -path '*/arm/*.cpp' | sort)
      ;;
    x86_64)
      # x86 needs per-file ISA flags (sse/avx/avx2/avx512); not implemented here —
      # build a generic-only zimg (no SIMD) so the binary is still correct.
      while IFS= read -r f; do srcs+=("$f"); done < <(find "$ZIMG_SRC/src/zimg" -path '*/x86/cpuinfo_x86.cpp')
      ;;
  esac
  rm -rf "$out"; mkdir -p "$out/obj" "$out/lib/pkgconfig" "$out/include"
  local i=0 objs=()
  for f in "${srcs[@]}"; do
    i=$((i+1))
    local o="$out/obj/$(printf '%03d' "$i")-$(basename "${f%.cpp}").o"
    clang++ "${flags[@]}" -c "$f" -o "$o" &
    objs+=("$o")
    # bound the fan-out to the core count
    while [[ "$(jobs -r | wc -l)" -ge "$(sysctl -n hw.ncpu)" ]]; do sleep 0.1; done
  done
  wait
  libtool -static -o "$out/lib/libzimg.a" "${objs[@]}" 2>/dev/null \
    || ar rcs "$out/lib/libzimg.a" "${objs[@]}"
  cp "$ZIMG_SRC/src/zimg/api/zimg.h" "$ZIMG_SRC/src/zimg/api/zimg++.hpp" "$out/include/"
  cat > "$out/lib/pkgconfig/zimg.pc" <<EOF
prefix=$out
exec_prefix=\${prefix}
libdir=\${exec_prefix}/lib
includedir=\${prefix}/include

Name: zimg
Description: Scaling, colorspace conversion, and dithering library
Version: $ZIMG_VERSION

Libs: -L\${libdir} -lzimg
Libs.private: -lc++
Cflags: -I\${includedir}
EOF
}

# ---------------------------------------------------------------- configure
# --disable-gpl is the default, but state it: this is the whole point of building.
COMMON_FLAGS=(
  --disable-gpl --disable-nonfree --disable-version3
  --enable-static --disable-shared
  --disable-doc --disable-htmlpages --disable-manpages --disable-podpages --disable-txtpages
  --disable-ffplay --disable-network
  # Hermetic: do not silently absorb whatever happens to be installed on the build
  # machine. But that also switches off zlib, and...
  --disable-autodetect
  # 🔴 ...ffmpeg declares exr_decoder_deps="zlib" AND png_decoder_deps="zlib".
  # Without this line the build succeeds, is LGPL, runs, reports its version happily -
  # and simply HAS NO EXR OR PNG SUPPORT. Nothing warns you; the codecs are just absent
  # from -decoders. Caught only because the verify step decodes a real EXR.
  --enable-zlib
  --enable-videotoolbox
  --enable-audiotoolbox
  # --disable-autodetect also means libzimg must be asked for explicitly, and it is
  # found ONLY through pkg-config (PKG_CONFIG_PATH points at our static build).
  --enable-libzimg
  --pkg-config-flags=--static
  --disable-debug
)

BUILT=()
if [[ "$VERIFY_ONLY" -eq 0 ]]; then
T0=$(date +%s)
for arch in "${ARCHS[@]}"; do
  say "building static zimg $ZIMG_VERSION for $arch"
  ZIMG_OUT="$WORK/zimg-$arch"
  build_zimg "$arch" "$ZIMG_OUT"
  [[ -s "$ZIMG_OUT/lib/libzimg.a" ]] || die "zimg build produced no library"
  say "  $(du -h "$ZIMG_OUT/lib/libzimg.a" | awk '{print $1}') libzimg.a"

  say "configuring ffmpeg for $arch"
  BUILD="$WORK/build-$arch"
  rm -rf "$BUILD"; mkdir -p "$BUILD"
  ( cd "$BUILD"
    PKG_CONFIG_PATH="$ZIMG_OUT/lib/pkgconfig" \
    "$SRC/configure" \
      --prefix="$BUILD/out" \
      --arch="$arch" \
      --cc="clang -arch $arch" \
      --extra-cflags="-arch $arch -mmacosx-version-min=11.0" \
      --extra-ldflags="-arch $arch -mmacosx-version-min=11.0" \
      --extra-libs="-lc++" \
      $([[ "$arch" != "$(uname -m)" ]] && echo --enable-cross-compile) \
      "${COMMON_FLAGS[@]}" > configure.log 2>&1 \
      || { tail -30 configure.log; die "configure failed for $arch (full log: $BUILD/configure.log)"; }
    say "building ffmpeg $arch (this takes a while)"
    make -j"$(sysctl -n hw.ncpu)" > build.log 2>&1 \
      || { tail -30 build.log; die "build failed for $arch (full log: $BUILD/build.log)"; }
  )
  BUILT+=("$BUILD")
done
say "build time: $(( $(date +%s) - T0 )) s"

# ---------------------------------------------------------------- combine + sign
for tool in ffmpeg ffprobe; do
  if [[ "${#BUILT[@]}" -gt 1 ]]; then
    say "lipo $tool into a universal binary"
    lipo -create -output "$VENDOR/$tool" "${BUILT[@]/%//$tool}"
  else
    cp "${BUILT[0]}/$tool" "$VENDOR/$tool"
  fi
  chmod +x "$VENDOR/$tool"
  # A downloaded/copied binary can carry quarantine, which is refused outright.
  xattr -dr com.apple.quarantine "$VENDOR/$tool" 2>/dev/null || true
done
fi

# 🔴 An unsigned binary on Apple Silicon is SIGKILLed with EMPTY stdout AND
# stderr - exit 137, no message anywhere, nothing to grep. Measured. Signing is
# not optional, and it must happen AFTER lipo, which invalidates any signature.
# The packager re-signs with the Developer ID (hardened runtime + timestamp) when
# it signs the app; --sign does that here so the vendored binary is already right.
for tool in ffmpeg ffprobe; do
  if [[ -n "$SIGN_ID" ]]; then
    say "signing $tool with '$SIGN_ID' (hardened runtime, timestamp)"
    codesign --force --options runtime --timestamp --sign "$SIGN_ID" "$VENDOR/$tool" \
      || die "codesign failed for $tool"
  elif [[ "$VERIFY_ONLY" -eq 0 ]]; then
    say "ad-hoc signing $tool"
    codesign -s - -f --timestamp=none "$VENDOR/$tool" 2>/dev/null \
      || die "codesign failed for $tool - the binary would be silently killed at runtime"
  fi
done

# ---------------------------------------------------------------- verify
# Every failure mode in this area is SILENT: SIGKILL prints nothing, a truncated
# frame decodes to exit 0. So verify by checking the OUTPUT, never the exit code.
say "verifying the build"
FIX="$WORK/verify"; rm -rf "$FIX"; mkdir -p "$FIX"

"$VENDOR/ffmpeg" -version >/dev/null 2>&1 \
  || die "ffmpeg will not run (exit $?). If this is 137 the signature did not take."
"$VENDOR/ffprobe" -version >/dev/null 2>&1 || die "ffprobe will not run"

# 🔴 Capture ONCE into a variable, then match with a here-string - never
# `cmd | grep -q`. Under `set -o pipefail`, grep -q exits on first match, the
# producer takes SIGPIPE (141), and pipefail propagates that as failure. So the
# pipeline reports FAILURE precisely when the match SUCCEEDS.
BANNER="$("$VENDOR/ffmpeg" -version 2>&1 || true)"
DECODERS="$("$VENDOR/ffmpeg" -hide_banner -decoders 2>/dev/null || true)"
ENCODERS="$("$VENDOR/ffmpeg" -hide_banner -encoders 2>/dev/null || true)"
FILTERS="$("$VENDOR/ffmpeg" -hide_banner -filters 2>/dev/null || true)"

[[ -n "$BANNER" ]] || die "ffmpeg produced no version output - if it was killed, the signature did not take"

if grep -q -- "--enable-gpl" <<<"$BANNER"; then
  die "this build is GPL, not LGPL - refusing to vendor it"
fi
say "  licence: LGPL confirmed (no --enable-gpl in configuration)"
grep -q -- "--enable-libzimg" <<<"$BANNER" || die "libzimg is not in the configuration"

for codec in exr dpx prores png h264 hevc; do
  grep -qE "^ V[^ ]* +$codec " <<<"$DECODERS" \
    || die "the '$codec' DECODER is missing from this build (zlib? --enable-zlib must be in COMMON_FLAGS)."
done
say "  decoders present: exr dpx prores png h264 hevc"
for enc in h264_videotoolbox png exr; do
  grep -qE "^ V[^ ]* +$enc " <<<"$ENCODERS" || die "the '$enc' ENCODER is missing from this build"
done
grep -qE "^ A[^ ]* +aac_at " <<<"$ENCODERS" || die "the 'aac_at' (AudioToolbox AAC) encoder is missing"
say "  encoders present: h264_videotoolbox png exr aac_at"
grep -qE " zscale " <<<"$FILTERS" || die "the zscale filter is missing - libzimg did not link"
say "  filters present: zscale"

# Write a half-float linear EXR and push it through zscale linear→sRGB.
"$VENDOR/ffmpeg" -hide_banner -loglevel error -y \
  -f lavfi -i "testsrc2=size=640x360:duration=1:rate=1" -frames:v 1 \
  -c:v exr -compression zip16 -format half "$FIX/probe.exr" 2>/dev/null \
  || die "could not write a test EXR - the exr encoder is missing from this build"

"$VENDOR/ffmpeg" -hide_banner -loglevel error -y -i "$FIX/probe.exr" \
  -frames:v 1 -vf "zscale=transferin=linear:transfer=iec61966-2-1:primariesin=709:primaries=709:matrix=709,format=yuv420p,scale=160:-1" \
  "$FIX/probe.jpg" 2>/dev/null \
  || die "could not decode the test EXR through zscale"

[[ -s "$FIX/probe.jpg" ]] || die "decode produced no output"

# ⚠️ -loglevel MUST be info here. `metadata=print` writes its output at INFO level,
# so the `-loglevel error` used everywhere else silently produces no measurement.
STATS="$("$VENDOR/ffmpeg" -hide_banner -loglevel info -i "$FIX/probe.jpg" \
  -vf "signalstats,metadata=print:key=lavfi.signalstats.YAVG" -f null - 2>&1 || true)"
MEAN="$(sed -n 's/.*YAVG=\([0-9.]*\).*/\1/p' <<<"$STATS" | head -1)"
if [[ -z "$MEAN" ]]; then
  say "  WARNING: could not measure output brightness - the black-image check DID NOT RUN"
elif awk -v m="$MEAN" 'BEGIN{exit !(m < 2.0)}'; then
  die "decoded EXR is essentially BLACK (mean luma $MEAN)"
else
  say "  EXR → zscale → JPEG produced real image data (mean luma $MEAN)"
fi

# h264_videotoolbox must actually encode (it needs the GPU; fails on some VMs).
"$VENDOR/ffmpeg" -hide_banner -loglevel error -y \
  -f lavfi -i "testsrc2=size=640x360:duration=1:rate=24" -pix_fmt yuv420p \
  -c:v h264_videotoolbox -b:v 2M -g 12 -keyint_min 12 \
  -movflags frag_keyframe+empty_moov+default_base_moof "$FIX/probe.mp4" 2>/dev/null \
  || die "h264_videotoolbox could not encode a test clip"
[[ -s "$FIX/probe.mp4" ]] || die "h264_videotoolbox produced an empty file"
say "  h264_videotoolbox fMP4 encode OK"

SIZE="$(du -ch "$VENDOR/ffmpeg" "$VENDOR/ffprobe" | tail -1 | awk '{print $1}')"
say "done: $VENDOR ($SIZE, $(lipo -archs "$VENDOR/ffmpeg" 2>/dev/null || echo '?'))"
say "vendor/ is gitignored - re-run this script rather than committing binaries"
